def css() -> str:
    ref = (HERE / "katalog-reference.css").read_text(encoding="utf-8")
    ref = ref[: ref.index("/* Full-bleed */")] + ref[ref.index("@media(max-width:1100px)"):]
    ref = ref.replace("#amt-cat", "#amt-svc")
    full = ref + "\n" + (HERE / "extra.css").read_text(encoding="utf-8")
    full = re.sub(r"/\*.*?\*/", "", full, flags=re.S)
    return re.sub(r"\s*\n\s*", "", full)


def esc(s: str) -> str:
    return html.escape(s, quote=True)


def media(key, alt, caption="", contain=False):
    u, w, h = IMG[key]
    cls = "amt-media amt-media--contain" if contain else "amt-media"
    cap = f"<figcaption>{caption}</figcaption>" if caption else ""
    return (f'<figure class="{cls}"><img src="{u}" alt="{esc(alt)}" width="{w}" height="{h}" loading="lazy">{cap}</figure>')


def head(eyebrow, title, lead=""):
    lead = f'<p class="amt-lead">{lead}</p>' if lead else ""
    return (f'<div class="amt-section__head"><div class="amt-section__copy"><div class="amt-eyebrow">{eyebrow}</div>'
            f'<h2 class="amt-title amt-title--section">{title}</h2>{lead}</div></div>')


def section(inner, sid="", soft=False):
    cls = "amt-section amt-section--soft" if soft else "amt-section"
    sid = f' id="{sid}"' if sid else ""
    return f'<section class="{cls}"{sid}><div class="amt-container">{inner}</div></section>'


def table(headers, rows):
    th = "".join(f"<th>{h}</th>" for h in headers)
    trs = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="amt-tablewrap"><table class="amt-table"><thead><tr>{th}</tr></thead><tbody>{trs}</tbody></table></div>'


def cards(items, cols=3):
    """items: (code, title, body_html, link_href|None, link_text)"""
    out = []
    for code, title, body, href, ltext in items:
        link = f'<div class="amt-link"><a class="amt-arrow" href="{href}">{ltext} <span>→</span></a></div>' if href else ""
        top = f'<div class="amt-tech__top"><span class="amt-code">{code}</span></div>' if code else ""
        out.append(f'<div class="amt-tech">{top}<div><h3>{title}</h3>{body}</div>{link}</div>')
    mod = {2: " amt-techs--2", 4: " amt-techs--4"}.get(cols, "")
    return f'<div class="amt-techs{mod}">' + "".join(out) + "</div>"


def steps(items, cols=None):
    cols = cols or len(items)
    mod = {3: " amt-uses--3", 5: " amt-uses--5"}.get(cols, "")
    out = "".join(f'<div class="amt-use"><div class="amt-use__num">{i:02d}</div><h3>{t}</h3><p>{d}</p></div>'
                  for i, (t, d) in enumerate(items, 1))
    return f'<div class="amt-uses{mod}">{out}</div>'


def checks(items):
    return '<ul class="amt-checks">' + "".join(f"<li>{x}</li>" for x in items) + "</ul>"


def dark(eyebrow, title, lead, models):
    """models: (label, name, [spec lines], href)"""
    n = len(models)
    mod = {3: " amt-models--3", 4: " amt-models--4"}.get(n, "")
    ms = []
    for label, name, spec, href in models:
        li = "".join(f"<li>{s}</li>" for s in spec)
        link = f'<div class="amt-link"><a class="amt-arrow" href="{href}">Подробнее <span>→</span></a></div>' if href else ""
        ms.append(f'<div class="amt-model"><div><div class="amt-model__label">{label}</div><div class="amt-model__name">{name}</div>'
                  f'<ul class="amt-model__spec">{li}</ul></div>{link}</div>')
    return (f'<div class="amt-lineup"><div class="amt-eyebrow">{eyebrow}</div><h2 class="amt-title amt-title--section">'
            f'{title}</h2><p class="amt-lead">{lead}</p><div class="amt-models{mod}">{"".join(ms)}</div></div>')


def faq(items):
    return '<div class="amt-faq">' + "".join(
        f"<details><summary>{q}</summary><p>{a}</p></details>" for q, a in items) + "</div>"


